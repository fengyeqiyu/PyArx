import json
OUT = r"G:\PyArx\tools\cadmcp\dbg_block.json"
P = globals().get("P")
if P is None:
    import PyArxCore as P
log = []
def rec(s):
    log.append(s)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(log, f, ensure_ascii=False, indent=1)
def _pt(x, y, z=0.0):
    return P.Ge.AcGePoint3d(float(x), float(y), float(z))
rec("start")
db = P.Db.curDb()
rec("curdb")
tr = P.Db.PyDbTrans()
rec("tr_new")
bt = tr.openObject(db.blockTableId(), 1)
rec("bt_open_w:" + type(bt).__name__)
btr = P.Db.PyDbBlockTableRecord()
rec("btr_new:" + type(btr).__name__)
btr.setName("PYARX_BLK")
rec("btr_setname")
bt.add(btr)
rec("bt_add")
tr.addNewlyCreatedDBObject(btr, True)
rec("btr_posted")
c = P.Db.PyDbCircle(_pt(0, 0), P.Ge.AcGeVector3d(0, 0, 1), 20.0)
rec("circle_new")
btr.appendAcDbEntity(c)
rec("circle_appended")
tr.addNewlyCreatedDBObject(c, True)
rec("circle_posted")
tr.commit()
rec("tr1_commit")
tr2 = P.Db.PyDbTrans()
bt2 = tr2.openObject(db.blockTableId(), 0)
rec("bt2_open_read:" + type(bt2).__name__)
rec2 = bt2.getAt("PYARX_BLK", 0)
rec("getAt:" + type(rec2).__name__ + ":" + str(rec2.objectId()))
br = P.Db.PyDbBlockReference()
rec("br_new:" + type(br).__name__)
br.setBlockTableRecord(rec2.objectId())
rec("br_setbtr")
br.setPosition(_pt(600, 0))
rec("br_setpos")
tr2.addEntity(br)
rec("br_addentity")
tr2.commit()
rec("done")
